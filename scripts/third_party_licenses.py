"""Writes licenses/THIRD_PARTY.TXT: every third-party Rust crate that the QBNex runtime
(qb-runtime, qb-audio) and the QIR runner (qb-exec) build or link, grouped by license.

Usage (from the repository root): python scripts/third_party_licenses.py
Needs cargo on PATH; reads Cargo.lock through `cargo metadata --locked`.
The list covers every target OS (Windows, Linux, macOS) and build-time crates.
"""
import collections
import json
import subprocess
import sys
from pathlib import Path

ROOTS = ("qb-runtime", "qb-audio", "qb-exec")


def main() -> int:
    repo = Path(__file__).resolve().parent.parent
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=repo, check=True, capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])

    seen, stack = set(), [i for i in workspace if packages[i]["name"] in ROOTS]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])

    by_license = collections.defaultdict(list)
    for pid in seen - workspace:
        p = packages[pid]
        by_license[p["license"] or "see crate"].append(f'{p["name"]} {p["version"]}')

    lines = [
        "Third-party Rust crates in the QBNex runtime (crates/qb-runtime, crates/qb-audio) and QIR runner",
        "(crates/qb-exec), grouped by license (SPDX expressions as published on crates.io).",
        "Generated by scripts/third_party_licenses.py from Cargo.lock; covers Windows, Linux and macOS",
        "and crates used only while building. Full license texts are in each crate's source package",
        "(https://crates.io/crates/<name>); Apache-2.0: license_apache_2_0.txt, MPL-2.0: license_mpl_2_0.txt.",
        "Where a crate offers a choice (\"A OR B\"), QBNex uses it under the most permissive option",
        "(MIT where offered).",
        "",
        f"{len(seen - workspace)} crates.",
    ]
    for lic, crates in sorted(by_license.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines += ["", f"License: {lic}", "  " + ", ".join(sorted(crates))]
    out = repo / "licenses" / "THIRD_PARTY.TXT"
    out.write_bytes(("\r\n".join(lines) + "\r\n").encode("utf-8"))
    print(f"wrote {out} ({len(seen - workspace)} crates, {len(by_license)} licenses)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

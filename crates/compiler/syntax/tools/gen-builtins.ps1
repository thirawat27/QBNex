# Regenerates crates/compiler/syntax/src/builtins_data.rs from the compiler's
# built-in registry (compiler/subs_functions/subs_functions.bas).
# Run from the repository root:  pwsh crates/compiler/syntax/tools/gen-builtins.ps1
$ErrorActionPreference = 'Stop'
$src = 'compiler/subs_functions/subs_functions.bas'
$out = 'crates/compiler/syntax/src/builtins_data.rs'
$entries = [ordered]@{}
$cur = $null
function Flush {
    if ($null -ne $script:cur -and $script:cur.name) {
        $key = $script:cur.name.ToUpperInvariant()
        if (-not $script:entries.Contains($key)) { $script:entries[$key] = $script:cur }
        elseif (-not $script:entries[$key].syntax -and $script:cur.syntax) { $script:entries[$key] = $script:cur }
    }
}
foreach ($line in Get-Content $src) {
    if ($line -match '^\s*clearid') { Flush; $cur = @{ name = $null; sub = 0; syntax = ''; must = '' }; continue }
    if ($null -eq $cur) { continue }
    if ($line -match 'id\.n\s*=\s*(qbnexprefix\$\s*\+\s*)?"([^"]+)"') {
        $cur.name = $(if ($matches[1]) { '_' } else { '' }) + $matches[2]
    }
    if ($line -match 'id\.subfunc\s*=\s*(\d)') { $cur.sub = [int]$matches[1] }
    if ($line -match 'id\.hr_syntax\s*=\s*"([^"]*)"') { $cur.syntax = $matches[1] }
    if ($line -match 'id\.musthave\s*=\s*"([^"]*)"') { $cur.must = $matches[1] }
}
Flush
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// @generated by crates/compiler/syntax/tools/gen-builtins.ps1 from')
[void]$sb.AppendLine('// compiler/subs_functions/subs_functions.bas. Do not edit by hand.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// (name, is_function, required suffix, syntax line)')
[void]$sb.AppendLine('pub(crate) static REGISTRY: &[(&str, bool, &str, &str)] = &[')
foreach ($k in ($entries.Keys | Sort-Object)) {
    $e = $entries[$k]
    $syn = $e.syntax.Replace('\', '\\').Replace('"', '\"')
    $isf = $(if ($e.sub -eq 1) { 'true' } else { 'false' })
    [void]$sb.AppendLine("    (`"$($k)`", $isf, `"$($e.must)`", `"$syn`"),")
}
[void]$sb.AppendLine('];')
[System.IO.File]::WriteAllText((Join-Path (Get-Location) $out), $sb.ToString())
"wrote $($entries.Count) entries"

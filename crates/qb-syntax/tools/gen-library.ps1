# Regenerates crates/qb-syntax/src/library_data.rs: the public SUBs and
# FUNCTIONs of the standard library modules under compiler/stdlib (ext.*,
# io.*, ...), for hover and completion. Run from the repository root:
#   pwsh crates/qb-syntax/tools/gen-library.ps1
$ErrorActionPreference = 'Stop'
$root = 'compiler/stdlib'
$out = 'crates/qb-syntax/src/library_data.rs'
$rows = [System.Collections.Generic.List[string]]::new()
$seen = @{}
$esc = { param($s) $s.Replace('\', '\\').Replace('"', '\"') }
foreach ($f in Get-ChildItem $root -Recurse -Filter *.bas | Sort-Object FullName) {
    $rel = [IO.Path]::GetRelativePath((Resolve-Path $root), $f.FullName) -replace '\\', '/'
    $module = ($rel -replace '\.bas$', '') -replace '/', '.'
    $inLib = $false
    $doc = [System.Collections.Generic.List[string]]::new()
    foreach ($line in Get-Content $f.FullName) {
        $t = $line.Trim()
        if ($t -match '^(?i)DECLARE\s+(DYNAMIC\s+|CUSTOMTYPE\s+|STATIC\s+)?LIBRARY') { $inLib = $true; continue }
        if ($t -match '^(?i)END\s+DECLARE') { $inLib = $false; continue }
        if ($t -match "^'\s?(.*)$") { $doc.Add($matches[1].Trim()); continue }
        if (-not $inLib -and $t -match '^(?i)(FUNCTION|SUB)\s+([A-Za-z_][\w.]*[%&!#$~`]*)\s*(\(.*\))?') {
            $kind = $matches[1].ToUpperInvariant()
            $name = $matches[2]
            $params = if ($matches[3]) { ' ' + $matches[3] } else { '' }
            $key = $name.ToUpperInvariant()
            if ($name -notmatch '^(?i)qb_' -and -not $seen.ContainsKey($key)) {
                $seen[$key] = 1
                $syntax = "$kind $name$params"
                $d = ($doc | Where-Object { $_ -ne '' -and $_ -notmatch '^[-=*]+$' }) -join ' '
                if ($d.Length -gt 300) { $d = $d.Substring(0, 300) + '...' }
                $isf = if ($kind -eq 'FUNCTION') { 'true' } else { 'false' }
                $rows.Add("    (`"$(& $esc $name)`", `"$module`", $isf, `"$(& $esc $syntax)`", `"$(& $esc $d)`"),")
            }
        }
        if ($t -ne '') { $doc.Clear() }
    }
}
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// @generated by crates/qb-syntax/tools/gen-library.ps1 from compiler/stdlib.')
[void]$sb.AppendLine('// Do not edit by hand.')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('/// (name, module, is_function, syntax, description)')
[void]$sb.AppendLine('pub(crate) static LIBRARY: &[(&str, &str, bool, &str, &str)] = &[')
foreach ($r in $rows) { [void]$sb.AppendLine($r) }
[void]$sb.AppendLine('];')
[System.IO.File]::WriteAllText((Join-Path (Get-Location) $out), $sb.ToString())
"wrote $($rows.Count) library procedures"

//! Generates the in-process symbol table of the qb-ext C ABI (`qb_ext_*`), so a
//! QIR program's `DECLARE LIBRARY` finds the extension library linked into the
//! runner before it looks at the platform's libraries.

use std::fmt::Write as _;

fn main() {
    let src_path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../runtime/ext/src/ffi.rs");
    println!("cargo:rerun-if-changed={}", src_path.display());
    let src = std::fs::read_to_string(&src_path).unwrap_or_default();
    let mut names: Vec<String> = Vec::new();
    for line in src.lines() {
        let t = line.trim_start();
        if !(t.starts_with("pub extern \"C\" fn ") || t.starts_with("pub unsafe extern \"C\" fn ")) {
            continue;
        }
        let rest = &t[t.find("fn ").map_or(0, |i| i + 3)..];
        let name: String = rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
        if name.starts_with("qb_ext_") {
            names.push(name);
        }
    }
    let mut out = String::from("/// `qb_ext_*` functions of the linked qb-ext crate (generated by build.rs).\n");
    out.push_str("pub(crate) fn ext_symbol(name: &str) -> Option<*const core::ffi::c_void> {\n    Some(match name {\n");
    for n in &names {
        let _ = writeln!(out, "        \"{n}\" => qb_ext::ffi::{n} as *const core::ffi::c_void,");
    }
    out.push_str("        _ => return None,\n    })\n}\n");
    let dest = std::path::Path::new(&std::env::var("OUT_DIR").unwrap_or_default()).join("ext_symbols.rs");
    let _ = std::fs::write(dest, out);
}
